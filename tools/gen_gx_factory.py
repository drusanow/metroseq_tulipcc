#!/usr/bin/env python3
"""Generate modules/mod_gintonix/core/gx_factory.c from the GinTonix factory
content (reference/gintonix/gintonic_presets.py): the drum sound library and
the factory kits.   python3 tools/gen_gx_factory.py"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, 'reference', 'gintonix'))
import gintonic_presets as P  # noqa: E402

KNOBS = ['mix', 'eq_freq', 'eq_gain', 'dist', 'level', 'pan', 'osc_freq', 'mod_amt', 'mod_rate',
         'osc_att', 'osc_dec', 'n_freq', 'n_q', 'n_att', 'n_dec', 'vel_osc', 'vel_noise', 'vel_mod']
KNOB_DEF = {'mix': 0.5, 'eq_freq': 0.5, 'eq_gain': 0.5, 'dist': 0.0, 'level': 0.5623, 'pan': 0.5,
            'osc_freq': 0.5, 'mod_amt': 0.5, 'mod_rate': 0.484, 'osc_att': 0.0, 'osc_dec': 0.5,
            'n_freq': 1.0, 'n_q': 0.17, 'n_att': 0.0, 'n_dec': 0.5, 'vel_osc': 0.0,
            'vel_noise': 0.0, 'vel_mod': 0.0}
SWITCHES = ['wave', 'mod_mode', 'n_mode', 'n_env', 'choke']
RATES = ['1/8', '1/8T', '1/16', '1/16T', '1/32']
FILLS = [2, 3, 4, 5, 6, 7, 8]


def c_str(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def patch(d):
    ks = ', '.join('%.6ff' % d.get(k, KNOB_DEF[k]) for k in KNOBS)
    ss = ', '.join('%d' % d.get(k, 0) for k in SWITCHES)
    return '{{%s}, {%s}}' % (ks, ss)


out = ['// gx_factory.c - GENERATED by tools/gen_gx_factory.py from',
       '// reference/gintonix/gintonic_presets.py. Do not edit; edit that file and re-run.',
       '#include <stddef.h>', '', '#include "gx_model.h"', '',
       'const gx_drum_t GX_DRUMS[] = {']
for name, d in P.DRUMS:
    out.append('    {%s, %s},' % (c_str(name), patch(d)))
out += ['};', 'const int GX_NDRUMS = %d;' % len(P.DRUMS), '']

for ki, (name, k) in enumerate(P.KITS):
    for letter, rows in sorted(k['patterns'].items()):
        out.append('static const char *const KIT%d_%s[] = {%s};' % (
            ki, letter, ', '.join(c_str(r) for r in rows)))
out += ['', 'const gx_kit_t GX_KITS[] = {']
for ki, (name, k) in enumerate(P.KITS):
    drums = ', '.join(c_str(d) for d in k['drums'])
    pats = ', '.join(('KIT%d_%s' % (ki, L)) if L in k['patterns'] else 'NULL'
                     for L in 'ABCDEFGHIJKL')
    rate = RATES.index(k.get('rate', '1/16'))
    fr = FILLS.index(int(k.get('fill', 2))) if int(k.get('fill', 2)) in FILLS else 0
    out.append('    {%s, {%s},\n     {%s},\n     %.1ff, %d, %d, %.1ff, %s},' % (
        c_str(name), drums, pats, float(k.get('tempo', 120)), rate, fr,
        float(k.get('swing', 0)), c_str(k.get('chain', ''))))
out += ['};', 'const int GX_NKITS = %d;' % len(P.KITS), '']

path = os.path.join(ROOT, 'modules', 'mod_gintonix', 'core', 'gx_factory.c')
with open(path, 'w') as f:
    f.write('\n'.join(out))
print('wrote', path, len(P.DRUMS), 'drums', len(P.KITS), 'kits')
