#!/usr/bin/env python3
"""Tulip Studio's app ABI: the functions and variables a loaded app (.elf) may use.

The list is every function and extern variable declared in the Studio's public
headers (studio/studio.h, studio/widgets.h; from studio/tclock.h the timeline functions), plus
components/tulip_studio/abi/extra.txt, plus the C library basics elf_loader
exports itself.

    tools/tulip_abi.py gen OUT.c            the firmware's export table
    tools/tulip_abi.py check APP.elf READELF  fail if the app needs anything else
    tools/tulip_abi.py list                 print the list
"""
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
INC = os.path.join(ROOT, "components", "tulip_studio", "include", "studio")
HEADERS = [os.path.join(INC, h) for h in ("studio.h", "widgets.h", "tclock.h")]
EXTRA = os.path.join(ROOT, "components", "tulip_studio", "abi", "extra.txt")
LOADER_SYMS = os.path.join(ROOT, "components", "elf_loader", "src", "esp_elf_symbol.c")


def header_symbols(path):
    s = open(path).read()
    s = re.sub(r"/\*.*?\*/", " ", s, flags=re.S)
    s = re.sub(r"//[^\n]*", " ", s)
    s = re.sub(r"#ifdef __cplusplus.*?#endif", " ", s, flags=re.S)
    s = re.sub(r"^\s*#[^\n]*(\\\n[^\n]*)*", " ", s, flags=re.M)
    # bodies and struct / enum members out (each brace block becomes a ';')
    while True:
        t = re.sub(r"\{[^{}]*\}", ";", s)
        if t == s:
            break
        s = t
    out = []
    for st in s.split(";"):
        st = " ".join(st.split())
        if not st or st.startswith(("typedef", "static")):
            continue
        m = re.match(r"^(?:extern\s+)?[\w\s\*]+?\b(\w+)\s*\([^()]*(?:\([^()]*\)[^()]*)*\)$", st)
        if m:
            out.append(m.group(1))
            continue
        m = re.match(r"^extern\s+[\w\s\*]+?\b(\w+)\s*(\[[^\]]*\])?$", st)
        if m:
            out.append(m.group(1))
    return out


def extra_symbols():
    out = []
    for line in open(EXTRA):
        line = line.split("#", 1)[0]
        out += line.split()
    return out


def loader_symbols():
    # elf_loader's C library table (its ESP-IDF one is off in Tulip Studio)
    s = open(LOADER_SYMS).read()
    s = s[s.index("g_esp_libc_elfsyms[]"):]
    s = s[:s.index("ESP_ELFSYM_END")]
    return re.findall(r"ESP_ELFSYM_EXPORT\((\w+)\)", s)


# the runtime's own: not for apps
PRIVATE = {"studio_run"}


def allowed(header, name):
    if name in PRIVATE:
        return False
    # the clock itself is the runtime's; apps read its timeline
    return not header.endswith("tclock.h") or name.startswith("tclock_tl_")


def ours():
    seen, out = set(), []
    for h in HEADERS:
        for n in header_symbols(h):
            if not allowed(h, n):
                continue
            if n not in seen:
                seen.add(n)
                out.append(n)
    for n in extra_symbols():
        if n not in seen:
            seen.add(n)
            out.append(n)
    return out


def gen(path):
    syms = [n for n in ours() if n not in set(loader_symbols())]
    with open(path + ".tmp", "w") as f:
        f.write("// Generated by tools/tulip_abi.py - the symbols a loaded app may use.\n")
        f.write("// Declared as bytes on purpose, with no headers: only their addresses\n")
        f.write("// matter here. The table has elf_loader's struct esp_elfsym layout.\n")
        f.write('#pragma GCC diagnostic ignored "-Wbuiltin-declaration-mismatch"\n\n')
        f.write("struct tulip_abi_sym {\n    const char *name;\n    const void *sym;\n};\n\n")
        for n in syms:
            f.write("extern char %s[];\n" % n)
        f.write("\nconst struct tulip_abi_sym g_tulip_abi_syms[] = {\n")
        for n in syms:
            f.write('    {"%s", (void *)%s},\n' % (n, n))
        f.write("    {0, 0},\n};\n")
        f.write("const int g_tulip_abi_count = %d;\n" % len(syms))
    os.replace(path + ".tmp", path)


def check(elf, readelf):
    have = set(ours()) | set(loader_symbols())
    txt = subprocess.run([readelf, "-W", "-s", elf], capture_output=True, text=True, check=True).stdout
    need = set()
    for line in txt.splitlines():
        p = line.split()
        # Num: Value Size Type Bind Vis Ndx Name
        if len(p) >= 8 and p[6] == "UND" and p[4] in ("GLOBAL", "WEAK") and p[7]:
            need.add(p[7].split("@")[0])
    missing = sorted(need - have)
    if missing:
        print("%s uses functions Tulip Studio doesn't export to apps:" % os.path.basename(elf))
        for n in missing:
            print("    " + n)
        print("Use another way, or add them to components/tulip_studio/abi/extra.txt\n"
              "(that needs a new studio.bin on the Tulip).")
        return 1
    print("%s: %d imports, all exported by Tulip Studio" % (os.path.basename(elf), len(need)))
    return 0


if __name__ == "__main__":
    if len(sys.argv) == 3 and sys.argv[1] == "gen":
        gen(sys.argv[2])
    elif len(sys.argv) == 4 and sys.argv[1] == "check":
        sys.exit(check(sys.argv[2], sys.argv[3]))
    elif len(sys.argv) == 2 and sys.argv[1] == "list":
        print("\n".join(ours()))
    else:
        print(__doc__)
        sys.exit(2)
